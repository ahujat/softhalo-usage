// Writes the snapshots this plugin produces for one scripted session into a
// Soft Halo fixture scenario, so Soft Halo's collector tests read the plugin's
// real output. The expected totals in that scenario are written by hand.
//
// Run: node tests/make-fixture.ts <path to Fixtures/AiUsage/plugin-output>
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { applyMeasure, applyStep, newSession, prepareWrite, type StepUsage } from '../hooks/core.ts'

const out = process.argv[2]
if (!out) throw new Error('usage: node tests/make-fixture.ts <scenario folder>')
mkdirSync(join(out, 'inputs'), { recursive: true })

const IST = 330
const at = (s: string) => Date.parse(s)
const u = (model: string, input: number, output: number, cacheRead: number, cacheWrite: number): StepUsage => ({
  model,
  input_tokens: input,
  output_tokens: output,
  cache_read_input_tokens: cacheRead,
  cache_creation_input_tokens: cacheWrite,
})

// A session that starts at 23:30 in India and runs past local midnight.
const state = newSession({
  sessionId: 'plug1',
  profile: 'p1',
  generation: 'g-plugin',
  nowMs: at('2026-11-07T18:00:05Z'),
  sessionStartedMs: at('2026-11-07T18:00:00Z'),
})
const steps: { name: string; input: string; now: string }[] = []
function flush(nowIso: string) {
  const w = prepareWrite(state, { nowMs: at(nowIso), utcOffsetMinutes: IST, pluginVersion: '1.0.0', appVersion: '2.1.317', ack: null })
  const input = `seq${w.seq}.json`
  writeFileSync(join(out, 'inputs', input), JSON.stringify(JSON.parse(w.text), null, 2) + '\n')
  steps.push({ name: `claude-plug1.${w.slot}.json`, input, now: nowIso })
  w.commit()
}

// 23:40 local, 7 Nov: one main-loop request.
applyStep(state, { key: 't1:0:', requestedModel: 'opus', usage: u('claude-opus-5-5', 100, 400, 1000, 50), finishedAtMs: at('2026-11-07T18:10:00Z'), utcOffsetMinutes: IST })
applyMeasure(state, { rateLimits: [{ kind: 'five_hour', percentUsed: 43, resetsAt: '2026-11-07T22:00:00Z' }], costUsd: 0.5, utcOffsetMinutes: IST }, at('2026-11-07T18:10:01Z'))
flush('2026-11-07T18:10:06Z')

// 00:10 local, 8 Nov: a subagent request on another model, then one with no usage.
applyStep(state, { key: 't2:0:a1', requestedModel: 'haiku', agentId: 'a1', usage: u('claude-haiku-5-5', 10, 20, 0, 0), finishedAtMs: at('2026-11-07T18:40:00Z'), utcOffsetMinutes: IST })
applyStep(state, { key: 't2:1:', requestedModel: 'claude-opus-5-5', usage: null, finishedAtMs: at('2026-11-07T18:41:00Z'), utcOffsetMinutes: IST })
// Spend after local midnight lands on 8 Nov.
applyMeasure(state, { rateLimits: [{ kind: 'five_hour', percentUsed: 43, resetsAt: '2026-11-07T22:00:00Z' }], costUsd: 0.8, utcOffsetMinutes: IST }, at('2026-11-07T18:41:05Z'))
// A repeated report of a request already counted changes nothing.
applyStep(state, { key: 't1:0:', requestedModel: 'opus', usage: u('claude-opus-5-5', 100, 400, 1000, 50), finishedAtMs: at('2026-11-07T18:41:30Z'), utcOffsetMinutes: IST })
flush('2026-11-07T18:41:10Z')

// Session end: the final flush, marked ended.
state.ended = true
state.dirty = true
flush('2026-11-07T18:50:00Z')

writeFileSync(
  join(out, 'steps.json'),
  JSON.stringify({ description: "Snapshots produced by the softhalo-usage plugin's own writer for a session that crosses local midnight (generated by softhalo-usage/tests/make-fixture.ts).", steps }, null, 2) + '\n',
)
console.log(`wrote ${steps.length} snapshots to ${out}`)
